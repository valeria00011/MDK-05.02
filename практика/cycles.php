<h1>Циклы</h1>

<h2>Цикл с параметром</h2>
<?php
for($i = 0; $i < 10; $i++){
    echo "$i <br>";
}
?>

<h2> Вложенный цикл</h2>
<?php
for($i = 0; $i < 5; $i++){
    for($j = 0; $j < 10; $j++){
        echo 'w';
    }
    echo '<br>';
}
?>

<h2>Операторы break и continue</h2>
<p>break - немедленный выход из текущего цикла</p>
<p>continue - переход к следующей итерации</p>